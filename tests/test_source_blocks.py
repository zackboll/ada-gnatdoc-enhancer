def independent_inputs(root, provenance):
    """Input-side authority retained independently of the submitted contract."""
    for name, expected in provenance['inputs'].items():
        path = root / name
        if any(p.is_symlink() for p in (path, *path.parents)) or digest(path.read_bytes()) != expected:
            raise EnhancementError('source differs from independent Git-export evidence')


class SourceBlocks(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.config = load(FIXTURE, CONFIG)
        cls.native = snapshot(cls.config, FIXTURE / 'native')
        cls.provenance = json.loads((FIXTURE / 'provenance.json').read_bytes())
        cls.expected = {p.relative_to(FIXTURE / 'reference').as_posix(): p.read_bytes()
                        for p in (FIXTURE / 'reference').rglob('*') if p.is_file()}

    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name) / 'source'
        shutil.copytree(FIXTURE, self.root)
        self.config = load(self.root, CONFIG)
        self.data = json.loads((self.root / 'docs/gnatdoc-authored.json').read_bytes())

    def reseal(self):
        self.data['inputs'] = {n: digest((self.root / n).read_bytes()) for n in self.data['inputs']}
        payload = sorted_json(self.data).encode()
        (self.root / 'docs/gnatdoc-authored.json').write_bytes(payload)
        self.config = replace(self.config, guide_sha256=digest(payload))

    def mutate_guide(self, name, transform):
        path = self.root / ('docs/guides/' + name + '.html')
        path.write_text(transform(path.read_text()))
        self.reseal()

    def reject(self):
        with self.assertRaises((EnhancementError, ValueError, TypeError, KeyError)):
            render(self.config, self.native)

    def test_exact_epoch_provenance_and_all_nine_portal_outputs(self):
        independent_inputs(self.root, self.provenance)
        self.assertEqual(hashes(FIXTURE / 'native'), self.provenance['native'])
        self.assertEqual(hashes(FIXTURE / 'reference'), self.provenance['reference'])
        output = render(self.config, self.native)
        reference = {n: b for n, b in self.expected.items() if not n.startswith('api/')}
        self.assertEqual(output, reference)
        self.assertEqual(len(output), 9)
        self.assertEqual(len(self.data['guides']), 7)

    def test_pipeline_inventory_native_parity_reconstruction_idempotence_determinism(self):
        site = self.root / 'native'
        enhance(self.config, site)
        first = hashes(site)
        verify(self.config, site)
        enhance(self.config, site)
        self.assertEqual(first, hashes(site))
        for name, expected in self.expected.items():
            if name != 'api/presentation.json':
                self.assertEqual((site / name).read_bytes(), expected, name)
        actual = json.loads((site / 'api/presentation.json').read_bytes())
        reference = json.loads(self.expected['api/presentation.json'])
        self.assertEqual(actual.pop('authored_source_blocks')['inputs'], self.data['inputs'])
        portal = {n: digest(b) for n, b in self.expected.items() if not n.startswith('api/')}
        self.assertEqual({n: v for n, v in actual['output_sha256'].items() if n in portal}, portal)
        actual['output_sha256'] = {n: v for n, v in actual['output_sha256'].items() if n not in portal}
        self.assertEqual(reference['enhancer_version'], '0.1.5')
        self.assertEqual(actual['enhancer_version'], '0.1.7')
        actual['enhancer_version'] = reference['enhancer_version']
        self.assertEqual(actual, reference)
        second = self.root / 'second'
        shutil.copytree(FIXTURE / 'native', second)
        enhance(self.config, second)
        self.assertEqual(first, hashes(second))
        # Resealing output-side hashes never authorizes forged generated bytes.
        page = site / 'guides/api-map.html'
        page.write_bytes(page.read_bytes().replace(b'No verified example use.', b'Compiler success. ', 1))
        actual = json.loads((site / 'api/presentation.json').read_bytes())
        actual['output_sha256']['guides/api-map.html'] = digest(page.read_bytes())
        (site / 'api/presentation.json').write_text(sorted_json(actual))
        with self.assertRaises(EnhancementError):
            verify(self.config, site)

