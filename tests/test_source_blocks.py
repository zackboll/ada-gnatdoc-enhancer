    def test_public_declaration_requires_regenerated_native_and_contract(self):
        epoch = FIXTURE.parent / 'epoch'
        evidence = json.loads((epoch / 'provenance.json').read_bytes())
        for name, expected in evidence['inputs'].items():
            self.assertEqual(digest((epoch / name).read_bytes()), expected)
        (self.root / 'ada/src/ams.ads').write_bytes((epoch / 'ams.ads').read_bytes())
        self.reject()  # Old source digest.
        self.reseal()
        with self.assertRaises(EnhancementError):
            snapshot(self.config, self.root / 'native')  # Old native has no new declaration.
        page = next(iter(evidence['native'].values()))['page']
        (self.root / 'native/api' / page).write_bytes((epoch / page).read_bytes())
        current = snapshot(self.config, self.root / 'native')
        with self.assertRaises(EnhancementError):
            render(self.config, current)  # Old native digest/anchor contract still fails.
        self.data['native_sha256']['api/' + page] = digest((epoch / page).read_bytes())
        ledger = self.root / self.data['anchors']
        anchors = json.loads(ledger.read_bytes()); anchors.update(evidence['native'])
        ledger.write_text(sorted_json(anchors)); self.reseal()
        output = render(self.config, current)
        self.assertIn(b'data-catalog-entry="AMS.Source_Epoch_Probe"', output['guides/api-map.html'])
        # Independent source epoch authority must also be regenerated, not just
        # the self-consistent contract supplied to the renderer.
        with self.assertRaises(EnhancementError):
            independent_inputs(self.root, self.provenance)

    def test_contract_schema_profile_digest_duplicates_and_guide_source(self):
        original = json.loads(json.dumps(self.data))
        for mutation in ('digest', 'schema', 'profile', 'unknown-field', 'duplicate-guide', 'native-digest'):
            self.data = json.loads(json.dumps(original))
            if mutation == 'schema': self.data['schema_version'] = 4
            if mutation == 'profile': self.data['source_blocks']['profile'] = 'callbacks-v1'
            if mutation == 'unknown-field': self.data['source_blocks']['html'] = '<p>forged</p>'
            if mutation == 'duplicate-guide': self.data['guides'][1] = self.data['guides'][0]
            if mutation == 'native-digest': self.data['native_sha256']['api/index.html'] = '0' * 64
            self.reseal()
            if mutation == 'digest': self.config = replace(self.config, guide_sha256='0' * 64)
            with self.subTest(mutation=mutation): self.reject()
        self.data = original; self.reseal()
        path = self.root / 'docs/guides/architecture.html'; value = path.read_bytes(); path.unlink()
        self.reject(); path.symlink_to(self.root / 'docs/index.html'); self.reject()
        path.unlink(); path.write_bytes(value)

    def test_malicious_source_roundtrips_as_escaped_inert_text(self):
        path = self.root / 'docs/examples/src/provider_session.adb'
        payload = b'-- <script onclick="bad()">& {{not-a-template}}</script>\n'
        path.write_bytes(path.read_bytes() + payload); self.reseal()
        # Literal template delimiters are prohibited by the portal contract even
        # inside escaped source; active markup without delimiters is inert text.
        self.reject()
        path.write_bytes(path.read_bytes().replace(b'{{not-a-template}}', b'not-a-template'))
        self.reseal()
        output = render(self.config, self.native)['guides/examples.html']
        self.assertIn(b'&lt;script onclick=&quot;bad()&quot;&gt;&amp;', output)

