    def test_ambiguous_operations_and_shadowed_aliases_remain_unlinked(self):
        blocks = Blocks(self.config, self.data, self.native)
        references = blocks.references
        key = next(k for k, ds in references.declarations.items()
                   if len(ds) == 1 and ds[0].declaration.kind == 'function')
        owner, _, name = key.rpartition('.')
        text = f'with {owner}; procedure Demo is package P renames {owner}; begin P.{name} (X); end;'
        self.assertTrue(any(r['context'] == 'unique-operation' for r in references.occurrences(text, 'demo')))
        references.declarations[key] *= 2
        self.assertFalse(any(r['context'] == 'unique-operation' for r in references.occurrences(text, 'demo')))
        references.declarations[key] = references.declarations[key][:1]
        text = text.replace('begin', 'P : Integer; begin')
        self.assertFalse(any(r['context'] == 'unique-operation' for r in references.occurrences(text, 'demo')))

