#!/usr/bin/env python3
"""Serial full-Geometry mutations; restore and verify before any browser run."""
import argparse
from dataclasses import replace
import json
from pathlib import Path
import shutil
import tempfile

from ada_gnatdoc_enhancer.config import load
from ada_gnatdoc_enhancer.pipeline import enhance, verify
from ada_gnatdoc_enhancer.qualification import hashes
from ada_gnatdoc_enhancer.util import digest, require, sorted_json


def run(workspace):
    root = workspace/'geometry-current'
    site = root/'first'
    config = load(root, 'qualification.toml')
    baseline = hashes(site)
    records = []
    source = root/'qualification-public/src/opencv-geometry.ads'
    manifest = site/'api/presentation.json'
    core = root/'dependency/native/api/ea2ebcbc108269c77d7c6d44d2dabdfb5f6d0179ad5622b1be3cbceaee5c44aa.html'
    page = site/'api/4f90dae6ae3d13b7eca2073a4084d7aafc29ca4b1a5df10de478124a1cd77135.html'
    correct = 'da696e09a1f1b297516365244e16533e23cca626f26df4bb3f727a64beb697b0'
    types = json.loads((root/'core-0.5.0-types.json').read_text())['types']
    wrong = types['opencv.rect']['anchor']
    require(wrong != correct and wrong.encode() in core.read_bytes(), 'wrong anchor must actually exist')

    def mutation(name, path, transform, action=None):
        before = path.read_bytes()
        changed = transform(before)
        require(before != changed, f'mutation not observed: {name}')
        path.write_bytes(changed)
        require(path.read_bytes() == changed, 'mutation not applied')
        try:
            try:
                (action or (lambda: verify(config, site)))()
            except ValueError as error:
                records.append({'name': name, 'observed': True, 'rejected': True,
                                'diagnostic': str(error), 'restored': False})
            else:
                raise ValueError(f'mutation accepted: {name}')
        finally:
            path.write_bytes(before)
            require(path.read_bytes() == before, 'failed byte restoration')
        require(hashes(site) == baseline, 'published hashes not restored')
        verify(config, site)
        records[-1]['restored'] = True

    mutation('changed-source-type-identity', source, lambda b: b.replace(
        b'subtype Contour is OpenCV.Point_Array;', b'subtype Contour is OpenCV.Rect;'))
    mutation('wrong-but-existing-published-Core-anchor', page,
             lambda b: b.replace(correct.encode(), wrong.encode(), 1))
    mutation('substituted-Core-native-bytes', core,
             lambda b: b.replace(b'type Point_Array is array', b'type Other_Array is array', 1))

    def forged_original(payload):
        data = json.loads(payload)
        name = 'api/'+page.name
        original = data['original_api_html'][name]
        data['original_api_html'][name] = original.replace(
            'subtype Contour is OpenCV.Point_Array;', 'subtype Contour is OpenCV.Rect;')
        require(data['original_api_html'][name] != original, 'native profile mutation not applied')
        return sorted_json(data).encode()
    mutation('forged-native-profile-in-output-manifest', manifest, forged_original)

    def forged_link(payload):
        data = json.loads(payload)
        # Wrong-but-existing target hash is not authority to change generated bytes.
        forged = page.read_bytes().replace(correct.encode(), wrong.encode(), 1)
        require(forged != page.read_bytes(), 'forged link did not change')
        data['output_sha256']['api/'+page.name] = digest(forged)
        return sorted_json(data).encode()
    mutation('forged-output-hash-cannot-authorize-link', manifest, forged_link)

    dep = {**config.dependencies[0], 'revision': 'ccc2190f9bf0712d65a2b9d2983cde7ce68b4bae'}
    require(dep['revision'] != config.dependencies[0]['revision'], 'revision substitution not applied')
    try:
        verify(replace(config, dependencies=(dep,)), site)
    except ValueError as error:
        records.append({'name': 'browser-fixture-substituted-for-Core-dependency',
                        'observed': True, 'rejected': True, 'restored': True,
                        'diagnostic': str(error)})
    else:
        raise ValueError('substituted dependency accepted')
    verify(config, site)

    with tempfile.TemporaryDirectory(prefix='subtype-atomic-') as temporary:
        raw = Path(temporary)/'site'
        shutil.copytree(workspace/'geometry-pristine', raw)
        before = hashes(raw)
        invalid = replace(config, dependencies=(dep,))
        try:
            enhance(invalid, raw)
        except ValueError as error:
            require(hashes(raw) == before, 'failed enhancement left partial output')
            records.append({'name': 'failed-enhancement-atomic', 'observed': True,
                            'rejected': True, 'restored': True, 'diagnostic': str(error)})
        else:
            raise ValueError('invalid enhancement accepted')
    require(hashes(site) == baseline, 'final restored inventory mismatch')
    verify(config, site)
    (workspace/'tampering.json').write_text(sorted_json({
        'mutations': records, 'restored_site_sha256': baseline,
        'publication_reverified_after_every_mutation': True}))
    print('PASS', len(records), 'observed, rejected, restored mutations')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--workspace', type=Path, required=True)
    run(parser.parse_args().workspace)